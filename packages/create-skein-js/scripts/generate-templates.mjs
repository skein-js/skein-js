#!/usr/bin/env node
// Generate `src/templates.generated.ts` — the scaffolder's project templates compiled into the JS
// bundle.
//
// Why templates live on disk: a contributor editing the starter graph should be looking at a
// TypeScript file, not at an array of quoted line strings. Authoring them as real files makes them
// diffable, reviewable, and free of the escaping hazard that comes with embedding code containing
// `${...}` inside a template literal.
//
// Why they are compiled in rather than read at runtime: `create-skein-js` ships two entry points —
// an ESM bin and CJS Nx generator factories — and locating a sibling directory differs between the
// two formats (`import.meta.url` vs `__dirname`). Compiling the sources into a plain module removes
// the question entirely, keeps `files` smaller, and follows the precedent set by
// packages/storage-postgres/scripts/generate-migrations.mjs. See docs/bundling.md.
//
// The `.tmpl` suffix is load-bearing: it keeps every template out of the workspace's eslint, tsc and
// vitest globs (all of which key on `.ts`), and it stops npm rewriting `gitignore.tmpl` the way it
// rewrites a real `.gitignore` inside a published tarball. `templates/` is listed in .prettierignore.
//
// Run `nx run create-skein-js:generate-templates` after editing one; `src/templates.test.ts` fails if
// the generated module drifts from the sources.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = path.join(packageRoot, "templates");
const outputFile = path.join(packageRoot, "src", "templates.generated.ts");

/** Every `.tmpl` file under `templates/`, as paths relative to that directory, sorted. */
async function findTemplateFiles(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const found = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const relativePath = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      found.push(...(await findTemplateFiles(path.join(directory, entry.name), relativePath)));
    } else if (entry.name.endsWith(".tmpl")) {
      found.push(relativePath);
    }
  }
  return found;
}

/** Escape template source for embedding in an untagged template literal. */
function escapeTemplateLiteral(contents) {
  return contents.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const templateFiles = await findTemplateFiles(templatesDir);
if (templateFiles.length === 0) throw new Error(`No .tmpl files found in ${templatesDir}`);

const templates = await Promise.all(
  templateFiles.map(async (file) => ({
    key: file.replace(/\.tmpl$/, ""),
    contents: await readFile(path.join(templatesDir, file), "utf8"),
  })),
);

const source = `// GENERATED by scripts/generate-templates.mjs — do not edit by hand.
// Source of truth: ../templates/**/*.tmpl. Run \`nx run create-skein-js:generate-templates\` after
// editing one; src/templates.test.ts fails if this drifts from the sources.

/**
 * Every project template, keyed by its path relative to \`templates/\` with the \`.tmpl\` suffix
 * dropped. Values are raw template source — see render-template.ts for the substitution syntax.
 */
export const TEMPLATE_SOURCES: Readonly<Record<string, string>> = {
${templates
  .map(({ key, contents }) => `  ${JSON.stringify(key)}: \`${escapeTemplateLiteral(contents)}\`,`)
  .join("\n")}
};
`;

const prettierConfig = await resolveConfig(outputFile);
await writeFile(
  outputFile,
  await format(source, { ...prettierConfig, parser: "typescript" }),
  "utf8",
);
console.log(`Wrote ${path.relative(packageRoot, outputFile)} from ${templates.length} templates.`);
